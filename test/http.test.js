import test from 'node:test';
import assert from 'node:assert/strict';
import { spawn } from 'node:child_process';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import net from 'node:net';
import { once } from 'node:events';
import { fileURLToPath } from 'node:url';
import { emptyDraft } from '../lib/campaign.js';

test('HTTP session, CSRF, draft persistence, CSV and preview work without SMTP', async t => {
  const reservation = net.createServer(); reservation.listen(0, '127.0.0.1'); await once(reservation, 'listening');
  const port = reservation.address().port; await new Promise(resolve => reservation.close(resolve));
  const directory = fs.mkdtempSync(path.join(os.tmpdir(), 'mail-studio-http-'));
  const proc = spawn(process.execPath, ['server.js'], { cwd: fileURLToPath(new URL('..', import.meta.url)), env: { ...process.env, HOST: '127.0.0.1', PORT: String(port), PUBLIC_ORIGIN: `http://127.0.0.1:${port}`, ADMIN_PASSWORD: '', GOOGLE_CLIENT_ID: 'test-client', GOOGLE_CLIENT_SECRET: 'test-secret', DATA_DIR: directory }, windowsHide: true });
  t.after(async () => { if (proc.exitCode === null) { proc.kill(); await once(proc, 'exit'); } fs.rmSync(directory, { recursive: true, force: true }); });
  await new Promise((resolve, reject) => { const timer = setTimeout(() => reject(new Error('Server startup timed out')), 10000); proc.stdout.on('data', data => { if (data.toString().includes('ready:')) { clearTimeout(timer); resolve(); } }); proc.once('error', reject); });
  const origin = `http://127.0.0.1:${port}`;
  assert.equal((await fetch(`${origin}/api/state`)).status, 401);
  const page = await fetch(origin); assert.equal(page.status, 200);
  const cookie = page.headers.get('set-cookie').split(';')[0];
  assert.match(page.headers.get('set-cookie'), /HttpOnly/);
  const state = await (await fetch(`${origin}/api/state?draft=1`, { headers: { Cookie: cookie } })).json();
  const headers = { Cookie: cookie, Origin: origin, 'Content-Type': 'application/json', 'X-CSRF-Token': state.csrf };
  const request = (route, value, extra = {}) => fetch(`${origin}/api/${route}`, { method: 'POST', headers: { ...headers, ...extra }, body: JSON.stringify(value) });
  assert.equal((await request('draft', {}, { Origin: 'https://evil.example' })).status, 403);
  assert.equal((await request('draft', {}, { 'X-CSRF-Token': 'wrong' })).status, 403);
  const value = { ...emptyDraft(), sender: 'sender@gmail.com', subject: 'Hello', message: 'Dear {{name}}', rows: [{ email: 'alex@example.com', name: 'Alex' }] };
  assert.equal((await request('draft', { draft: value })).status, 200);
  const preview = await (await request('preview', { draft: value })).json();
  assert.equal(preview.messages[0].text, 'Dear Alex');
  const csv = await (await request('csv', { csv: 'email,name\na@example.com,Alex' })).json();
  assert.equal(csv.rows[0].name, 'Alex');
  assert.equal((await request('start', {})).status, 400);
  assert.deepEqual(state.google, { configured: true, email: null });
  assert.equal((await request('google/connect', {}, { 'X-CSRF-Token': 'wrong' })).status, 403);
  const connection = await (await request('google/connect', {})).json();
  const googleUrl = new URL(connection.url);
  assert.equal(googleUrl.hostname, 'accounts.google.com');
  assert.equal(googleUrl.searchParams.get('redirect_uri'), `${origin}/auth/google/callback`);
  const rejected = await fetch(`${origin}/auth/google/callback?state=wrong&code=fake`, { headers: { Cookie: cookie }, redirect: 'manual' });
  assert.equal(rejected.status, 303);
  assert.equal(rejected.headers.get('location'), '/');
  const after = await (await fetch(`${origin}/api/state`, { headers: { Cookie: cookie } })).json();
  assert.match(after.googleNotice, /expired/);
  assert.equal(after.google.email, null);
  assert.equal((await request('google/disconnect', {})).status, 200);
  assert.equal((await fetch(`${origin}/data/campaign.json`, { headers: { Cookie: cookie } })).status, 403);
  assert.equal(JSON.parse(fs.readFileSync(path.join(directory, 'campaign.json'))).draft.subject, 'Hello');
});
